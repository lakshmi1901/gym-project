CREATE TABLE IF NOT EXISTS accounts (
 id VARCHAR(191) COLLATE utf8mb4_bin PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL,
 passwordHash VARCHAR(255) NOT NULL,
 createdAt VARCHAR(40),
 passwordChangedAt VARCHAR(40),
 tokenVersion INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users_info (
 id VARCHAR(191) COLLATE utf8mb4_bin PRIMARY KEY,
 record JSON NOT NULL,
 name VARCHAR(255) GENERATED ALWAYS AS (JSON_UNQUOTE(JSON_EXTRACT(record, '$.Name'))) VIRTUAL,
 phone VARCHAR(64) GENERATED ALWAYS AS (JSON_UNQUOTE(JSON_EXTRACT(record, '$.Phone_Number'))) VIRTUAL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
